window.LANG = localStorage.getItem("okey-lang") || "de";
window.t = function (k) {
  const pack = window.I18N[window.LANG] || window.I18N.de;
  return pack[k] || window.I18N.de[k] || k;
};
window.applyI18n = function () {
  document.documentElement.lang = window.LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    el.textContent = window.t(k);
  });
  document.querySelectorAll(".lang-btn").forEach((b) => {
    b.classList.toggle("on", b.getAttribute("data-lang") === window.LANG);
  });
};
window.setLang = function (code) {
  window.LANG = code;
  localStorage.setItem("okey-lang", code);
  window.applyI18n();
};
